from django.test import TestCase
from decimal import Decimal
from clients.models import Client


class ClientModelTests(TestCase):
    def test_client_code_autogenerated_when_blank(self):
        client1 = Client.objects.create(
            name='Rajesh Builders',
            phone='9876543210',
            payment_type=Client.PAYMENT_TYPE_CREDIT,
            credit_limit=Decimal('50000.00')
        )
        self.assertTrue(client1.code.startswith('CLT-'))
        self.assertEqual(client1.payment_type, Client.PAYMENT_TYPE_CREDIT)
        self.assertFalse(client1.is_cash_client)

        client2 = Client.objects.create(
            name='Modern Homes',
            phone='9876543211',
            payment_type=Client.PAYMENT_TYPE_CASH
        )
        self.assertTrue(client2.code.startswith('CLT-'))
        self.assertNotEqual(client1.code, client2.code)
        self.assertTrue(client2.is_cash_client)

    def test_client_custom_code_preserved(self):
        client = Client.objects.create(
            name='Prime Constructions',
            code='PRIME-001',
            phone='9876543212',
            payment_type=Client.PAYMENT_TYPE_CASH
        )
        self.assertEqual(client.code, 'PRIME-001')

    def test_cash_client_credit_logic(self):
        client = Client.objects.create(
            name='Direct Cash Customer',
            phone='9876543213',
            payment_type=Client.PAYMENT_TYPE_CASH,
            credit_limit=Decimal('0.00'),
            opening_balance=Decimal('0.00')
        )
        self.assertTrue(client.is_cash_client)
        self.assertEqual(client.available_credit, Decimal('0.00'))
        self.assertFalse(client.is_credit_exceeded)

        # If a cash client has an outstanding balance on their account, credit is exceeded
        client.account.current_balance = Decimal('100.00')
        client.account.save()
        self.assertTrue(client.is_credit_exceeded)
